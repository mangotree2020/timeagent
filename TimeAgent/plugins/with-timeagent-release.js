const {
  AndroidConfig,
  withAndroidManifest,
  withAppBuildGradle,
} = require('expo/config-plugins');

const DEFINITION_MARKER = '// @generated by with-timeagent-release: signing definitions';

function findBlockEnd(source, blockStart) {
  const openingBrace = source.indexOf('{', blockStart);
  if (openingBrace < 0) throw new Error('Android Gradle block opening brace not found.');

  let depth = 0;
  for (let index = openingBrace; index < source.length; index += 1) {
    if (source[index] === '{') depth += 1;
    if (source[index] === '}') depth -= 1;
    if (depth === 0) return index;
  }
  throw new Error('Android Gradle block closing brace not found.');
}

function addReleaseSigning(buildGradle) {
  let source = buildGradle;

  if (!source.includes(DEFINITION_MARKER)) {
    const projectRootLine = /def projectRoot = .*\n/;
    if (!projectRootLine.test(source)) {
      throw new Error('Unable to find projectRoot in android/app/build.gradle.');
    }
    const definitions = `${DEFINITION_MARKER}\n`
      + 'def releaseStoreFilePath = System.getenv("TIMEAGENT_UPLOAD_STORE_FILE") ?: findProperty("TIMEAGENT_UPLOAD_STORE_FILE")\n'
      + 'def releaseStorePassword = System.getenv("TIMEAGENT_UPLOAD_STORE_PASSWORD") ?: findProperty("TIMEAGENT_UPLOAD_STORE_PASSWORD")\n'
      + 'def releaseKeyAlias = System.getenv("TIMEAGENT_UPLOAD_KEY_ALIAS") ?: findProperty("TIMEAGENT_UPLOAD_KEY_ALIAS")\n'
      + 'def releaseKeyPassword = System.getenv("TIMEAGENT_UPLOAD_KEY_PASSWORD") ?: findProperty("TIMEAGENT_UPLOAD_KEY_PASSWORD")\n'
      + 'def releaseRequested = gradle.startParameter.taskNames.any { it.toLowerCase().contains("release") }\n'
      + 'def hasReleaseSigning = releaseStoreFilePath && releaseStorePassword && releaseKeyAlias && releaseKeyPassword\n';
    source = source.replace(projectRootLine, (match) => `${match}${definitions}`);
  }

  const signingStart = source.indexOf('    signingConfigs {');
  if (signingStart < 0) throw new Error('Unable to find signingConfigs in android/app/build.gradle.');
  const signingEnd = findBlockEnd(source, signingStart);
  const signingBlock = source.slice(signingStart, signingEnd + 1);
  if (!signingBlock.includes('if (hasReleaseSigning)')) {
    const releaseConfig = [
      '        if (hasReleaseSigning) {',
      '            release {',
      '                storeFile file(releaseStoreFilePath)',
      '                storePassword releaseStorePassword',
      '                keyAlias releaseKeyAlias',
      '                keyPassword releaseKeyPassword',
      '            }',
      '        }',
    ].join('\n');
    source = `${source.slice(0, signingEnd)}${releaseConfig}\n    ${source.slice(signingEnd)}`;
  }

  const buildTypesStart = source.indexOf('    buildTypes {');
  if (buildTypesStart < 0) throw new Error('Unable to find buildTypes in android/app/build.gradle.');
  const buildTypesEnd = findBlockEnd(source, buildTypesStart);
  const releaseTypeStart = source.indexOf('        release {', buildTypesStart);
  if (releaseTypeStart < 0 || releaseTypeStart > buildTypesEnd) {
    throw new Error('Unable to find the release build type in android/app/build.gradle.');
  }
  const releaseTypeEnd = findBlockEnd(source, releaseTypeStart);
  const releaseTypeBlock = source.slice(releaseTypeStart, releaseTypeEnd + 1);
  if (!releaseTypeBlock.includes('TimeAgent release signing credentials are required')) {
    const unsafeSigning = '            signingConfig signingConfigs.debug';
    if (!releaseTypeBlock.includes(unsafeSigning)) {
      throw new Error('Unable to find the default release signing configuration.');
    }
    const safeSigning = [
      '            if (!hasReleaseSigning && releaseRequested) {',
      '                throw new GradleException("TimeAgent release signing credentials are required. Run npm run release:android.")',
      '            }',
      '            if (hasReleaseSigning) signingConfig signingConfigs.release',
    ].join('\n');
    const updatedBlock = releaseTypeBlock.replace(unsafeSigning, safeSigning);
    source = `${source.slice(0, releaseTypeStart)}${updatedBlock}${source.slice(releaseTypeEnd + 1)}`;
  }

  return source;
}

function withTimeAgentRelease(config) {
  config = withAppBuildGradle(config, (gradleConfig) => {
    if (gradleConfig.modResults.language !== 'groovy') {
      throw new Error('TimeAgent release signing currently supports Groovy build.gradle only.');
    }
    gradleConfig.modResults.contents = addReleaseSigning(gradleConfig.modResults.contents);
    return gradleConfig;
  });

  return withAndroidManifest(config, (manifestConfig) => {
    const manifest = manifestConfig.modResults.manifest;
    const application = AndroidConfig.Manifest.getMainApplicationOrThrow(
      manifestConfig.modResults,
    );
    application.$['android:allowBackup'] = 'false';

    const removedPermissions = [
      'android.permission.READ_EXTERNAL_STORAGE',
      'android.permission.WRITE_EXTERNAL_STORAGE',
      'android.permission.SYSTEM_ALERT_WINDOW',
    ];
    manifest['uses-permission'] = manifest['uses-permission'] ?? [];
    for (const permissionName of removedPermissions) {
      const existing = manifest['uses-permission'].find(
        (permission) => permission.$?.['android:name'] === permissionName,
      );
      if (existing) {
        existing.$['tools:node'] = 'remove';
      } else {
        manifest['uses-permission'].push({
          $: { 'android:name': permissionName, 'tools:node': 'remove' },
        });
      }
    }
    return manifestConfig;
  });
}

module.exports = withTimeAgentRelease;
module.exports.addReleaseSigning = addReleaseSigning;
